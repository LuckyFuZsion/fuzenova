// Builds docs/prompt-pack.html (copy buttons + progress tracker) and docs/ART_PROMPTS.md from tools/sheet-plan.mjs.
// Usage: node tools/build-prompt-pack.mjs
import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { SHEETS, BRANDING } from './sheet-plan.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
mkdirSync(join(root, 'docs'), { recursive: true });

const STYLE = `Art style for a 2D top-down factory-building game called "Cinder Automata": a burnt, ash-covered alien world rebuilt with rugged industrial machines. Hand-painted digital game art with clean readable silhouettes, soft ambient occlusion, subtle worn-metal texture, thick dark outlines, muted charcoal / rust / soot-grey palette with warm ember-orange and amber glow accents. Strict top-down orthographic view (looking straight down, no perspective), lit from the top-left. NO cast shadows on the background, no text, no labels, no numbers, no borders, no grid lines, no watermark. Every object sits on a perfectly flat solid pure magenta (#FF00FF) background, with generous empty magenta space between objects so no two objects touch or overlap. Do not use magenta anywhere inside the objects.`;

const KIND = {
  object: '',
  icon: 'These are small inventory-style icons: each is a single flat object seen from directly above, with a chunky, thick, clean silhouette that stays readable when shrunk to 24 pixels.',
  tile: 'Each item is a perfectly square, edge-to-edge filled tile texture with no magenta inside the square and no border. Tiles must be able to sit beside copies of themselves without a visible seam. Leave clear magenta gaps BETWEEN the tiles.',
  creature: 'Everything here is drawn top-down, facing right unless stated otherwise, in the same painted style, with no ground shadow.',
  fx: 'These are visual effects: they may have soft glowing edges but need solid bright cores, and no magenta inside them.',
  ui: 'Flat game-UI art: bold simple front-on shapes, thick dark outline, ember-orange as the single accent colour, no text or letters. (This sheet is NOT top-down machines.)',
};

const COLS = { 3: 3, 4: 2, 5: 3, 6: 3, 7: 4, 8: 4, 9: 3, 10: 5, 11: 4, 12: 4, 16: 4 };

function prompt(s) {
  const n = s.items.length;
  const cols = COLS[n] ?? 4;
  const lines = s.items.map(([name, desc], i) => `${i + 1}. ${desc || name.replace(/-/g, ' ')}`).join('\n');
  return [
    STYLE,
    KIND[s.kind],
    s.note,
    'Match the art style, palette, outline weight and lighting of the attached reference image exactly.',
    n === 1
      ? `Draw exactly ONE object, centred on the canvas: ${s.items[0][1] || s.items[0][0]}`
      : `Sheet: ${s.title}. Draw exactly ${n} separate objects in a neat grid of about ${cols} per row, in this reading order (left to right, top row first):`,
    n === 1 ? '' : lines,
    `Leave generous empty magenta space around every object. Do not draw any text.${n >= 9 ? ' Use a wide landscape canvas.' : ''}`,
  ].filter(Boolean).join('\n\n');
}

const todo = SHEETS.filter((s) => !s.done && !s.cut);
const cutSheets = SHEETS.filter((s) => s.cut);
const objects = todo.reduce((a, s) => a + s.items.length, 0);
const tierName = { 1: 'Tier 1 - the fight loop: combat, robots, ammo chain, resources', 2: 'Tier 2 - depth and polish', 3: 'Tier 3 - optional extras' };

// ---------- markdown ----------
let md = `# Cinder Automata - Gemini prompt pack\n\nGenerated by \`node tools/build-prompt-pack.mjs\` from \`tools/sheet-plan.mjs\`. **${todo.length} sheets, ${objects} objects** still to generate.\n\n`;
md += `## Workflow\n1. Attach an already-good sheet (e.g. \`sheet-01-logistics\`) to EVERY prompt as the style reference.\n2. Paste the prompt. Save the result as \`art/raw/<file>.png\` (or .jpg) using the file name shown.\n3. Run \`node tools/slice-sheets.mjs\` and check \`art/contact/<file>.png\`.\n4. If the object count is wrong or things touch, regenerate that sheet.\n\n`;
for (const t of [1, 2, 3]) {
  md += `## ${tierName[t]}\n\n`;
  for (const s of todo.filter((x) => x.tier === t)) {
    md += `### Sheet ${s.id} - ${s.title} (${s.items.length}) \n\`art/raw/${s.file}.png\`\n\n\`\`\`\n${prompt(s)}\n\`\`\`\n\n`;
  }
}
md += `## Cut sheets (no longer needed for the fight-loop design)\n\n${cutSheets.map((s) => `- Sheet ${s.id} - ${s.title}`).join('\n')}\n\n`;
md += `## Branding art (not sliced)\n\n`;
for (const b of BRANDING) md += `### ${b.id} - ${b.title}\n\n\`\`\`\n${b.prompt}\n\`\`\`\n\n`;
writeFileSync(join(root, 'docs', 'ART_PROMPTS.md'), md);

// ---------- html ----------
const esc = (t) => t.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const card = (id, title, meta, text, file) => `
<article class="card" data-id="${id}">
  <header>
    <label class="done"><input type="checkbox" data-done="${id}"> generated</label>
    <h3>${esc(title)}</h3><span class="meta">${meta}</span>
  </header>
  ${file ? `<div class="file">save as <code>art/raw/${file}.png</code></div>` : ''}
  <pre>${esc(text)}</pre>
  <button data-copy="${id}">Copy prompt</button>
</article>`;

let body = '';
for (const t of [1, 2, 3]) {
  body += `<section data-tier="${t}"><h2>${tierName[t]}</h2>`;
  for (const s of todo.filter((x) => x.tier === t)) {
    body += card(`s${s.id}`, `Sheet ${s.id} - ${s.title}`, `${s.items.length} objects`, prompt(s), s.file);
  }
  body += '</section>';
}
body += '<section data-tier="b"><h2>Branding art (not sliced, text allowed)</h2>';
for (const b of BRANDING) body += card(b.id, `${b.id} - ${b.title}`, 'single image', b.prompt, null);
body += '</section>';

const html = `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Cinder Automata - prompt pack</title>
<style>
:root{--bg:#120e0c;--panel:#1c1613;--line:#3a2f28;--text:#ece4da;--dim:#a89c8e;--accent:#ff8a1f}
*{box-sizing:border-box}body{margin:0;background:var(--bg);color:var(--text);font:15px/1.5 system-ui,sans-serif}
main{max-width:980px;margin:0 auto;padding:24px 16px 80px}
h1{margin:0 0 4px}h2{margin:36px 0 12px;color:var(--accent);font-size:15px;letter-spacing:.08em;text-transform:uppercase}
.sub{color:var(--dim)}.bar{position:sticky;top:0;background:var(--bg);padding:10px 0;border-bottom:1px solid var(--line);display:flex;gap:16px;align-items:center;flex-wrap:wrap;z-index:5}
.progress{flex:1;min-width:160px;height:8px;background:var(--panel);border-radius:4px;overflow:hidden}.progress i{display:block;height:100%;width:0;background:var(--accent)}
.card{background:var(--panel);border:1px solid var(--line);border-radius:10px;padding:14px;margin:0 0 12px}
.card.is-done{opacity:.45}.card header{display:flex;gap:12px;align-items:baseline;flex-wrap:wrap}
.card h3{margin:0;font-size:16px}.meta{color:var(--dim);font-size:13px}.done{margin-left:auto;font-size:13px;color:var(--dim);order:3}
.file{color:var(--dim);font-size:13px;margin:6px 0}code{background:#000;padding:1px 6px;border-radius:4px;color:#e8c77a}
pre{white-space:pre-wrap;background:#0d0a09;border:1px solid var(--line);border-radius:8px;padding:12px;font:13px/1.45 ui-monospace,Consolas,monospace;max-height:220px;overflow:auto}
button{background:var(--accent);color:#1a0e02;border:0;border-radius:8px;padding:8px 16px;font:600 14px system-ui;cursor:pointer}button.ok{background:#5ec27a}
.filters label{margin-right:10px;color:var(--dim);cursor:pointer}
@media(max-width:600px){.done{margin-left:0}}
</style></head><body><main>
<h1>Cinder Automata prompt pack</h1>
<p class="sub">${todo.length} sheets, ${objects} objects. Attach a finished sheet (e.g. sheet 01) as the style reference to every prompt. Copy buttons include the full style block.</p>
<div class="bar"><span id="count"></span><div class="progress"><i id="fill"></i></div>
<span class="filters"><label><input type="checkbox" id="hideDone"> hide generated</label></span></div>
${body}
</main>
<script>
const KEY='cinder-prompt-pack-done';let done={};try{done=JSON.parse(localStorage.getItem(KEY)||'{}')}catch(e){}
const cards=[...document.querySelectorAll('.card')];
function refresh(){let n=0;for(const c of cards){const d=!!done[c.dataset.id];c.classList.toggle('is-done',d);c.querySelector('[data-done]').checked=d;if(d)n++;
 c.hidden=document.getElementById('hideDone').checked&&d}
 document.getElementById('count').textContent=n+' / '+cards.length+' generated';document.getElementById('fill').style.width=(100*n/cards.length)+'%'}
document.addEventListener('change',e=>{const id=e.target.dataset&&e.target.dataset.done;if(id){done[id]=e.target.checked;try{localStorage.setItem(KEY,JSON.stringify(done))}catch(_){}}refresh()});
document.getElementById('hideDone').addEventListener('change',refresh);
document.addEventListener('click',async e=>{const id=e.target.dataset&&e.target.dataset.copy;if(!id)return;
 const text=document.querySelector('[data-id="'+id+'"] pre').textContent;
 try{await navigator.clipboard.writeText(text)}catch(_){const r=document.createRange();r.selectNodeContents(document.querySelector('[data-id="'+id+'"] pre'));getSelection().removeAllRanges();getSelection().addRange(r);document.execCommand('copy')}
 e.target.textContent='Copied!';e.target.classList.add('ok');setTimeout(()=>{e.target.textContent='Copy prompt';e.target.classList.remove('ok')},1400)});
refresh();
</script></body></html>`;
writeFileSync(join(root, 'docs', 'prompt-pack.html'), html);
console.log(`${todo.length} sheets / ${objects} objects -> docs/prompt-pack.html and docs/ART_PROMPTS.md`);
